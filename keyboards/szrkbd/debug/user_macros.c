bool process_record_user(uint16_t keycode, keyrecord_t *record) {
  uint8_t row = record->event.key.row;
  uint8_t col = record->event.key.col;
  uprintf("[%c] Key pressed at row %u, col %u\n",
		  is_keyboard_master() ? 'm' : 's',
		  row, col);

	const int8_t led = grid2led[row][col];

  if (record->event.pressed) {
	keyheat[led].down = true;
	keyheat[led].colour = palette_index;
	keyheat[led].heat =
	  ((uint32_t)keyheat[led].heat + HEATADD) > HEATMAX
	  ? HEATMAX
	  : (uint16_t)((uint32_t)keyheat[led].heat + HEATADD);

	palette_index = (palette_index+1) & 0xff;

	switch(keycode) {
	case UM_ANGL:
	  SEND_STRING("<>");
	  tap_code(KC_LEFT);
	  return false;
	case UM_SQUA:
	  SEND_STRING("[]");
	  tap_code(KC_LEFT);
	  return false;
	case UM_CURL:
	  SEND_STRING("{}");
	  tap_code(KC_LEFT);
	  return false;
	case UM_PARN:
	  SEND_STRING("()");
	  tap_code(KC_LEFT);
	  return false;
	}

	if( macos && !send_french_macos(keycode) ) {
	  return false;
	}

	if( !macos && !send_french_windows(keycode) ) {
	  return false;
	}
  }
  else {
	keyheat[led].down = false;
  }
  
  return true;
}
