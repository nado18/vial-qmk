struct {
  uint8_t colour;
  uint16_t heat;
  bool down;
} keyheat[18];
#define LEDS sizeof(keyheat)/sizeof(keyheat[0])

const int8_t grid2led[4][5] = {
  { 4, 3, 2, 1, 0},
  { 9, 8, 7, 6, 5},
  {14,13,12,11,10},
  {17,16,15,-1,-1}
};

#define HEATMAX 65535
#define HEATADD HEATMAX
#define HEATSUB 1024

bool rgb_matrix_indicators_user(void) {
    rgb_matrix_set_color_all(0, 0, 0);

	for(int i=0; i<LEDS; i++) {
	  const uint32_t heat = keyheat[i].heat;
	  if( heat <= 0 ) continue;

	  const uint8_t colour = keyheat[i].colour;
	  
	  const uint8_t r = (heat * palette[colour].r) >> 16;
	  const uint8_t g = (heat * palette[colour].g) >> 16;
	  const uint8_t b = (heat * palette[colour].b) >> 16;

	  /*
	  uprintf(
			  "[colour=%u] (%lu * %u = %u) (%lu * %u = %u) (%lu * %u = %u)\n",
			  colour,
			  heat, palette[colour].r, r,
			  heat, palette[colour].g, g,
			  heat, palette[colour].b, b
			  );
	  */

	  rgb_matrix_set_color(i, r, g, b);

	  if( keyheat[i].down ) continue;

	  keyheat[i].heat =
		keyheat[i].heat <= HEATSUB
		? 0
		: keyheat[i].heat - HEATSUB;
	}
	
    rgb_matrix_update_pwm_buffers();
    return false;
}

