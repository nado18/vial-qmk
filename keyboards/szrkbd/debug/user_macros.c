bool macos = false;
bool process_detected_host_os_kb(os_variant_t detected_os) {
  if (!process_detected_host_os_user(detected_os)) {
	return false;
  }

  switch (detected_os) {
  case OS_MACOS:
  case OS_IOS:
	macos = true;
	break;
  default:
	break;
  }
  return true;
}

